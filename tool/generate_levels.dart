// Generates the 30 curated levels into assets/levels/ and the difficulty
// table into docs/difficulty_table.md.
//
//   dart run tool/generate_levels.dart
//
// Every level comes from the seeded generator, is re-checked by the solver
// and validator, and is chosen from many seeds by a "trickiness" score so the
// curve rises smoothly. Output is deterministic: rerunning gives identical
// files.

import 'dart:convert';
import 'dart:io';

import 'package:jinhop/core/core.dart';

class Spec {
  final int id;
  final int size;
  final int frogs;
  final int chain;
  final int rotators;
  final int snakes;
  final int slack;
  final bool gentle; // L1-5: pick the least tricky candidate
  const Spec(this.id, this.size, this.frogs, this.chain, this.rotators, this.snakes, this.slack,
      {this.gentle = false});
  int get world => id <= 15 ? 1 : 2;
}

const specs = <Spec>[
  // World 1 "Misty Pond": core rule only (never fail).
  Spec(1, 6, 12, 4, 0, 0, 99, gentle: true),
  Spec(2, 6, 12, 5, 0, 0, 99, gentle: true),
  Spec(3, 6, 12, 5, 0, 0, 99, gentle: true),
  Spec(4, 6, 13, 6, 0, 0, 99, gentle: true),
  Spec(5, 6, 13, 7, 0, 0, 99, gentle: true),
  // Rotators arrive.
  Spec(6, 6, 12, 5, 1, 0, 7),
  Spec(7, 6, 13, 6, 2, 0, 7),
  Spec(8, 6, 13, 6, 2, 0, 6),
  Spec(9, 6, 14, 7, 2, 0, 6),
  Spec(10, 6, 14, 7, 3, 0, 6),
  Spec(11, 6, 14, 8, 3, 0, 6),
  Spec(12, 6, 15, 8, 3, 0, 5),
  Spec(13, 6, 15, 9, 3, 0, 5),
  Spec(14, 6, 16, 9, 4, 0, 5),
  Spec(15, 6, 16, 10, 4, 0, 5),
  // World 2 "Lantern Marsh": rotators + snakes, then 7x7.
  Spec(16, 6, 14, 7, 2, 1, 5),
  Spec(17, 6, 14, 7, 2, 2, 5),
  Spec(18, 6, 15, 8, 3, 2, 5),
  Spec(19, 6, 15, 8, 3, 2, 5),
  Spec(20, 6, 16, 9, 3, 2, 5),
  Spec(21, 7, 16, 9, 3, 2, 4),
  Spec(22, 7, 17, 9, 3, 2, 4),
  Spec(23, 7, 17, 10, 4, 3, 4),
  Spec(24, 7, 18, 10, 4, 3, 4),
  Spec(25, 7, 18, 11, 4, 3, 4),
  Spec(26, 7, 19, 11, 4, 3, 4),
  Spec(27, 7, 20, 12, 5, 3, 3),
  Spec(28, 7, 20, 12, 5, 3, 3),
  Spec(29, 7, 21, 13, 5, 4, 3),
  Spec(30, 7, 22, 13, 5, 4, 3),
];

class Scored {
  final GeneratedLevel g;
  final int score;
  final int wrongFirst;
  final int traps;
  final double randomWin;
  Scored(this.g, this.score, this.wrongFirst, this.traps, this.randomWin);
}

/// Share of 400 random players who win within the cap (par + 5 for the
/// never-fail levels). Each player taps a uniformly random free frog, except
/// that it always takes the golden frog when it is free. Lower = harder.
double randomWinRate(Level level) {
  final b = Board(level);
  final cap = level.unlimitedBudget ? level.par + 5 : level.cap;
  final rng = Rng(level.seed ?? 1);
  var wins = 0;
  const runs = 400;
  for (var r = 0; r < runs; r++) {
    var m = b.fullMask;
    var used = 0;
    while (used < cap) {
      if (b.canTap(m, b.goldenIndex)) {
        used++;
        wins++;
        break;
      }
      final moves = b.tappableFrogs(m);
      if (moves.isEmpty) break;
      m &= ~(1 << rng.pick(moves));
      used++;
    }
  }
  return wins / runs;
}

/// Target random-player win rate: falls smoothly from L6 to L30.
double targetWin(int id) => id <= 5 ? 1.0 : 0.65 - (id - 6) * (0.65 - 0.10) / 24;

/// Trickiness: how many first moves are not on any shortest path, and how
/// many valid moves anywhere on the main line lead to an unwinnable or
/// over-budget state.
Scored score(GeneratedLevel g) {
  final b = Board(g.level);
  final s = Solver(b);
  final par = g.level.par;
  final cap = g.level.unlimitedBudget ? 1 << 20 : g.level.cap;
  var wrongFirst = 0;
  for (final f in b.tappableFrogs(b.fullMask)) {
    if (f == b.goldenIndex) continue;
    final d = s.minRemaining(b.fullMask & ~(1 << f));
    if (d == null || d != par - 1) wrongFirst++;
  }
  var traps = 0;
  var m = b.fullMask;
  final path = s.solutionPath(m)!;
  for (var i = 0; i < path.length - 1; i++) {
    for (final f in b.tappableFrogs(m)) {
      if (f == b.goldenIndex || f == path[i]) continue;
      final d = s.minRemaining(m & ~(1 << f));
      if (d == null || d + i + 1 > cap) traps++;
    }
    m &= ~(1 << path[i]);
  }
  var turned = 0;
  for (var i = 0; i < path.length; i++) {
    if (b.onRotator[path[i]] && i % 4 != 0) turned++;
  }
  return Scored(g, wrongFirst * 2 + traps * 3 + turned * 2, wrongFirst, traps, randomWinRate(g.level));
}

void main() {
  const gen = LevelGenerator();
  final outDir = Directory('assets/levels')..createSync(recursive: true);
  final table = StringBuffer()
    ..writeln('# JinHop difficulty table')
    ..writeln()
    ..writeln('Generated by `dart run tool/generate_levels.dart`. Par is solver-computed.')
    ..writeln()
    ..writeln('| Level | World | Grid | Frogs | Par | Rotators | Snakes | budgetSlack | Cap | Decoys | Wrong first moves | Random-player win % | Seed |')
    ..writeln('|---|---|---|---|---|---|---|---|---|---|---|---|---|');

  for (final sp in specs) {
    final cfg = GeneratorConfig(
      size: sp.size,
      frogCount: sp.frogs,
      chainLength: sp.chain,
      rotatorCount: sp.rotators,
      snakeCount: sp.snakes,
      requireRotatorOnChain: sp.rotators > 0,
      minPar: sp.chain <= 4 ? 4 : sp.chain - 1,
      blockedDecoyBias: sp.gentle ? 0.8 : 0.6,
    );
    final candidates = <Scored>[];
    for (var k = 0; k < 300 && candidates.length < 60; k++) {
      final seed = sp.id * 1000 + k;
      final g = gen.generate(cfg, seed: seed, id: sp.id, world: sp.world, budgetSlack: sp.slack);
      if (g == null) continue;
      if (g.level.par < sp.chain - 1) continue;
      // L1 must teach by play: at least one decoy that is blocked at the start.
      if (sp.id == 1) {
        final b = Board(g.level);
        final path = Solver(b).solutionPath(b.fullMask)!.toSet();
        final blockedDecoy = [
          for (var f = 0; f < b.frogCount; f++)
            if (!path.contains(f) && !b.canTap(b.fullMask, f)) f
        ];
        if (blockedDecoy.isEmpty) continue;
      }
      candidates.add(score(g));
    }
    if (candidates.isEmpty) {
      stderr.writeln('Level ${sp.id}: no candidate found');
      exitCode = 1;
      return;
    }
    // Gentle levels: the easiest for a random player, but a wrong move must
    // exist. Others: closest to the target difficulty curve.
    double key(Scored c) => sp.gentle ? -c.randomWin : (c.randomWin - targetWin(sp.id)).abs();
    candidates.sort((a, b) {
      final c = key(a).compareTo(key(b));
      return c != 0 ? c : a.g.level.seed! - b.g.level.seed!;
    });
    final pick = sp.gentle
        ? candidates.firstWhere((c) => c.wrongFirst > 0, orElse: () => candidates.first)
        : candidates.first;
    final level = pick.g.level.copyWith(rotatorIntro: sp.id == 6);
    final v = LevelValidator.validate(level);
    if (!v.ok) {
      stderr.writeln('Level ${sp.id} failed validation: $v');
      exitCode = 1;
      return;
    }
    final name = 'level_${sp.id.toString().padLeft(2, '0')}.json';
    File('${outDir.path}/$name').writeAsStringSync('${const JsonEncoder.withIndent('  ').convert(level.toJson())}\n');
    final cap = level.unlimitedBudget ? 'none' : '${level.cap}';
    table.writeln('| ${sp.id} | ${sp.world} | ${sp.size}x${sp.size} | ${level.frogs.length} | ${level.par} | '
        '${level.rotatorCount} | ${level.snakes.length} | ${level.budgetSlack} | $cap | ${v.decoys} | '
        '${pick.wrongFirst} | ${(pick.randomWin * 100).round()}% | ${level.seed} |');
    stdout.writeln('L${sp.id}: par ${level.par}, frogs ${level.frogs.length}, random win '
        '${(pick.randomWin * 100).round()}% (target ${(targetWin(sp.id) * 100).round()}%, '
        '${candidates.length} candidates)');
  }
  Directory('docs').createSync();
  File('docs/difficulty_table.md').writeAsStringSync(table.toString());
}
